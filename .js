function abrirPopup(id) {

    const datos = informacion[id];

    if (!datos) {

        console.error("No existe información para:", id);

        return;

    }

    document.getElementById("popup-titulo").textContent =
        datos.titulo;

    document.getElementById("popup-imagen").src =
        datos.imagen;

    document.getElementById("popup-imagen").alt =
        datos.titulo;

    document.getElementById("popup-descripcion1").textContent =
        datos.descripcion1;

            document.getElementById("popup-descripcion2").textContent =
        datos.descripcion2;

    document.getElementById("popup").style.display = "flex";

    document.body.style.overflow = "hidden";

}


function cerrarPopup() {

    document.getElementById("popup").style.display = "none";

    document.body.style.overflow = "";

}


document.addEventListener("keydown", function(event) {

    if (event.key === "Escape") {

        cerrarPopup();

    }

});